"""Query current C-Route and generate the reproducible M2 six-station result."""

from __future__ import annotations

import csv
import hashlib
import json
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from backend.app.engine.service import RouteEngine
from backend.app.sim.adapters import ODRouteSet, routes_from_c_route_output
from backend.app.sim.m2 import run_m2_multi_od


STATIONS = ("TAW", "KOT", "MKK", "HUH", "EXC", "ADM")
SEED = 20260922
POPULATION = 10_000
WINDOW_MIN = 60
TIME_RANGE = ("08:00", "09:00")
DEPART_AT = "2026-09-22T08:20:00+08:00"
SCENARIO_ID = "m2_six_station_directed_od_am_peak"


def _json_write(path: Path, value: object) -> None:
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def _route_key(route: dict) -> tuple:
    return (
        route.get("route_id"),
        tuple((leg.get("mode"), leg.get("from"), leg.get("to"), leg.get("line_id"), leg.get("accessible")) for leg in route.get("legs", [])),
        route.get("total", {}).get("time_s"),
        route.get("total", {}).get("transfers"),
    )


def main() -> None:
    out_dir = ROOT / "data" / "sim"
    engine = RouteEngine.from_seed()
    od_payloads: list[dict] = []
    route_sets: list[ODRouteSet] = []
    query_errors: list[dict] = []

    for origin in STATIONS:
        for destination in STATIONS:
            if origin == destination:
                continue
            merged_routes: dict[str, dict] = {}
            merged_params: dict[str, dict] = {}
            query_records = []
            for profile_name, profile in (
                ("standard", {"mobility": "standard", "preset": "fastest"}),
                ("wheelchair", {"mobility": "wheelchair", "preset": "fastest", "max_walk_m": 400, "max_transfers": 2}),
            ):
                try:
                    result = engine.query_details(origin, destination, DEPART_AT, profile, limit=10)
                except (KeyError, ValueError) as exc:
                    query_errors.append({"origin": origin, "destination": destination,
                                         "profile": profile_name, "error": str(exc)})
                    result = {"routes": [], "route_parameters": {}, "diagnostics": [str(exc)]}
                query_records.append({"profile": profile_name, "candidate_count": len(result.get("routes", [])),
                                      "diagnostics": result.get("diagnostics", [])})
                if not result.get("routes"):
                    continue
                routes, _ = routes_from_c_route_output(result, fixture=True)
                for raw_route in result["routes"]:
                    route_id = raw_route["route_id"]
                    previous = merged_routes.get(route_id)
                    if previous is None or profile_name == "wheelchair":
                        merged_routes[route_id] = raw_route
                    raw_param = dict(result["route_parameters"][route_id])
                    previous_param = merged_params.get(route_id)
                    if previous_param is not None and previous_param != raw_param:
                        raise ValueError(f"{origin}->{destination} {route_id}: profile queries returned conflicting route_parameters")
                    merged_params[route_id] = raw_param

            # Preserve no-route ODs explicitly. Adapter validates all non-empty
            # candidate sets against the frozen route_parameters contract.
            od_item = {
                "origin": origin,
                "destination": destination,
                "demand_weight": 1.0,
                "provenance": "simulated",
                "routes": list(merged_routes.values()),
                "route_parameters": merged_params,
                "query_records": query_records,
            }
            od_payloads.append(od_item)
            if merged_routes:
                routes, supplies = routes_from_c_route_output(
                    {"routes": od_item["routes"], "route_parameters": merged_params}, fixture=True
                )
            else:
                routes, supplies = (), ()
            route_sets.append(ODRouteSet(origin, destination, routes, supplies, 1.0, "simulated"))

    assumptions = [
        "All six stations form 30 directed OD pairs; each pair receives equal simulated demand weight because verified OD demand is unavailable.",
        "Population is 10,000 generated by the C-Sim fixed-seed population generator (seed 20260922); persona shares and arrival assumptions remain simulated.",
        "Routes and route_parameters are queried from the current seed-backed C-Route RouteEngine at 2026-09-22T08:20:00+08:00; SeedDataAdapter forces network and fares to simulated provenance.",
        "Each OD candidate set is the union of current C-Route standard and wheelchair query results, capped at 10 candidates per profile; no candidate is synthesized to fill a shortfall.",
        "Route IDs are consumed unchanged. If an identical route_id occurs across ODs, its route-level supply is counted once globally after semantic equality checks.",
        "C-Route exposes route-level bottleneck capacity, not capacity by physical segment/service identity. Distinct route IDs that share legs cannot be safely de-duplicated; this remains an explicit model limitation.",
        "No verified passenger demand, residual load, service-day calendar, or operator vehicle capacity is connected; all resulting metrics remain simulated algorithm outputs.",
        "Baseline assigns each passenger to their own best accessible candidate. Guided applies the shared route-id target/physical capacities, wheelchair accessibility filter, and 15-minute extra-delay limit.",
    ]
    input_doc = {
        "input_version": "m2-six-station-v1",
        "scenario_id": SCENARIO_ID,
        "source_revision": "working-tree",
        "data_version": {
            "network_file": "contracts/seed/network.seed.json",
            "network_sha256": hashlib.sha256((ROOT / "contracts/seed/network.seed.json").read_bytes()).hexdigest(),
            "route_policy_file": "backend/app/engine/fixtures/seed_policy.json",
            "route_policy_sha256": hashlib.sha256((ROOT / "backend/app/engine/fixtures/seed_policy.json").read_bytes()).hexdigest(),
        },
        "route_engine": "backend.app.engine.service.RouteEngine.from_seed().query_details",
        "depart_at": DEPART_AT,
        "stations": list(STATIONS),
        "od_count": len(od_payloads),
        "population": POPULATION,
        "seed": SEED,
        "time_range": list(TIME_RANGE),
        "window_min": WINDOW_MIN,
        "classification": "simulated",
        "od_route_sets": od_payloads,
        "query_errors": query_errors,
        "assumptions": assumptions,
        "provenance": "simulated",
    }
    _json_write(out_dir / "m2-route-input.json", input_doc)
    manifest = {
        "manifest_version": "1.1",
        "milestone": "M2 interim six-station multi-OD simulation",
        "scenario_id": SCENARIO_ID,
        "source_revision": input_doc["source_revision"],
        "input_file": "data/sim/m2-route-input.json",
        "result_file": "data/sim/m2-simulation-result.json",
        "classification": "simulated",
        "policy": (
            "References identify inputs but do not upgrade simulated values to real or real-derived. "
            "All route, demand, population, and capacity values in this scenario remain simulated."
        ),
        "inputs": [
            {
                "field": "population_and_persona_shares",
                "value": POPULATION,
                "classification": "simulated",
                "source": "backend/app/sim/population.py",
                "note": "Fixed-seed synthetic population and persona shares; not observed passenger data.",
            },
            {
                "field": "random_seed",
                "value": SEED,
                "classification": "simulated",
                "source": "scripts/precompute_sim_m2.py",
                "note": "Fixed only for reproducibility; it is not an observed value.",
            },
            {
                "field": "stations_and_directed_od_pairs",
                "value": STATIONS,
                "classification": "simulated",
                "source": "scripts/precompute_sim_m2.py",
                "note": "Six selected corridor stations produce 30 directed OD pairs with equal simulated demand weights.",
            },
            {
                "field": "route_candidates_and_accessibility",
                "value": "Seed-backed C-Route query at the fixed departure time",
                "classification": "simulated",
                "source": input_doc["data_version"]["network_file"],
                "reference": input_doc["data_version"]["route_policy_file"],
                "note": "The seed adapter forces simulated provenance; route candidates are not verified service guarantees.",
            },
            {
                "field": "headway_and_route_capacity_parameters",
                "value": "C-Route route_parameters from the current seed-backed engine",
                "classification": "simulated",
                "source": input_doc["data_version"]["route_policy_file"],
                "note": "Scenario estimates are not operator-reported headways, vehicle capacity, or residual capacity.",
            },
            {
                "field": "departure_time_and_service_window",
                "value": {"depart_at": DEPART_AT, "time_range": TIME_RANGE, "window_min": WINDOW_MIN},
                "classification": "simulated",
                "source": "scripts/precompute_sim_m2.py",
                "note": "The scenario does not resolve the service window through data/calendar.json.",
            },
        ],
        "known_gaps": [
            "No verified passenger-demand, residual-load, or operator capacity feed is connected.",
            "Service-day and public-holiday rules from data/calendar.json are not applied to this fixed-time scenario.",
            "Capacity is counted by route_id; overlapping physical line segments across distinct route IDs cannot be pooled or partitioned with the current C-Route contract.",
            "Results are algorithm demonstrations and must not be presented as measured passenger flows, verified operational capacity, or operational forecasts.",
        ],
    }
    _json_write(out_dir / "m2-input-manifest.json", manifest)

    result = run_m2_multi_od(
        scenario_id=SCENARIO_ID,
        route_sets=tuple(route_sets),
        population=POPULATION,
        seed=SEED,
        window_min=WINDOW_MIN,
        time_range=TIME_RANGE,
        assumptions=assumptions,
    )
    result.update({
        "input_file": "data/sim/m2-route-input.json",
        "route_query_error_count": len(query_errors),
        "no_route_od_count": sum(not item["routes"] for item in od_payloads),
        "query_time": DEPART_AT,
        "data_version": input_doc["data_version"],
        "generated_at": datetime.now().astimezone().isoformat(timespec="seconds"),
        "provenance": "simulated" if all(item["provenance"] == "simulated" for item in od_payloads) else "mixed",
    })
    line_route_ids: dict[str, set[str]] = {}
    for od_item in od_payloads:
        for route in od_item["routes"]:
            for leg in route.get("legs", []):
                line = leg.get("line")
                if line and leg.get("mode") != "WALK":
                    line_route_ids.setdefault(str(line), set()).add(route["route_id"])
    shared_lines = {
        line: {"distinct_route_id_count": len(route_ids), "route_ids": sorted(route_ids)}
        for line, route_ids in sorted(line_route_ids.items())
        if len(route_ids) > 1
    }
    result["capacity_model"]["shared_line_overlap"] = {
        "line_count": len(shared_lines),
        "lines": shared_lines,
        "interpretation": "Distinct full-path route_ids can consume the same simulated line. The current C-Route contract exposes only each path's bottleneck capacity, so these capacities cannot be conservatively partitioned by shared line without segment-level supply identities.",
    }
    _json_write(out_dir / "m2-simulation-result.json", result)

    rows = [
        ("延误总量（人·分钟）", result["baseline"]["total_delay_person_min"], result["guided"]["total_delay_person_min"]),
        ("平均延误（分钟/人）", result["baseline"]["avg_delay_min"], result["guided"]["avg_delay_min"]),
        ("物理运力已服务人数", result["baseline"]["served_demand"], result["guided"]["served_demand"]),
        ("未满足需求（物理运力口径）", result["baseline"]["unmet_demand"], result["guided"]["unmet_demand"]),
        ("未分配需求", result["baseline"]["unassigned_demand"], result["guided"]["unassigned_demand"]),
        ("超目标容量路线数", result["baseline"]["overloaded_routes"], result["guided"]["overloaded_routes"]),
        ("轮椅乘客服务率", result["baseline"]["wheelchair_served_rate"], result["guided"]["wheelchair_served_rate"]),
        ("无障碍候选集缺失 OD 数", sum(row["wheelchair_candidate_count"] == 0 for row in result["od_results"]), sum(row["wheelchair_candidate_count"] == 0 for row in result["od_results"])),
    ]
    with (out_dir / "m2-comparison.csv").open("w", encoding="utf-8-sig", newline="") as stream:
        writer = csv.writer(stream)
        writer.writerow(["指标", "baseline", "guided"])
        writer.writerows(rows)
    md = [
        "# M2 六站多 OD 仿真对比",
        "",
        f"- provenance：`{result['provenance']}`；seed：`{SEED}`；OD：`{result['od_count']}`；候选路线：`{result['candidate_count']}`（去重 ID `{result['unique_route_id_count']}`）",
        f"- 无路线 OD：`{result['no_route_od_count']}`；查询错误：`{len(query_errors)}`；跨 OD 重复 route_id：`{result['shared_route_id_count']}`",
        "- 结果为模拟算法输出；不能解释为实测客流、真实运力或运营预测。",
        f"- 共享线路段：{len(shared_lines)} 条线路对应多个 route_id；当前路线级容量不能按共享线路拆分。",
        "",
        "| 指标 | baseline | guided |",
        "|---|---:|---:|",
    ]
    md.extend(f"| {label} | {before} | {after} |" for label, before, after in rows)
    delay_delta = result["delta"]["delay_reduction_pct"]
    if delay_delta < 0:
        interpretation = (
            f"本场景 guided 总延误比 baseline 高 {abs(delay_delta):.1f}%；"
            "两组均未出现目标容量超载或未满足需求，因此本次结果没有显示引导策略带来延误收益。"
        )
    elif delay_delta > 0:
        interpretation = (
            f"本场景 guided 总延误比 baseline 低 {delay_delta:.1f}%；"
            "该收益仅适用于下述模拟输入与运力假设，不是实测效果。"
        )
    else:
        interpretation = "本场景 guided 与 baseline 总延误相同；不能据此声称引导策略降低延误。"
    md += ["", "## 本次结果解读", "", interpretation,
           "", "## 数据与运力限制", "", result["capacity_model"]["note"],
           "", "不同路线可能共享部分线路或区段；当前接口没有按区段暴露可分配运力。结果中的 route_id 容量桶无法扣除这种重叠，所以 0 未满足需求只表示当前模拟模型的结果，不能解释为真实网络有足够运力。", ""]
    (out_dir / "m2-comparison.md").write_text("\n".join(md), encoding="utf-8")
    print(json.dumps({
        "input": "data/sim/m2-route-input.json",
        "result": "data/sim/m2-simulation-result.json",
        "comparison": "data/sim/m2-comparison.csv",
        "od_count": result["od_count"],
        "candidate_count": result["candidate_count"],
        "no_route_od_count": result["no_route_od_count"],
        "shared_route_id_count": result["shared_route_id_count"],
        "baseline_served": result["baseline"]["served_demand"],
        "guided_served": result["guided"]["served_demand"],
    }, ensure_ascii=False))


if __name__ == "__main__":
    main()
